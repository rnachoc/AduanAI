package io.github.rnachoc.aduana.cli.attacks;

import java.util.Comparator;
import java.util.List;
import java.util.Map;

/**
 * Writes `attacks/REPORT.md`: the same results always give the same bytes, so CI can tell when the
 * committed report is out of date.
 *
 * @author Ignacio Rodríguez Caro <rnachoccontact@gmail.com>
 */
public final class Report {

  /**
   * Not instantiated.
   *
   * @author Ignacio Rodríguez Caro <rnachoccontact@gmail.com>
   */
  private Report() {}

  /**
   * Renders the report.
   *
   * @param results the results, in any order
   * @return the Markdown text
   * @author Ignacio Rodríguez Caro <rnachoccontact@gmail.com>
   */
  public static String render(List<CaseResult> results) {
    List<CaseResult> sorted =
        results.stream().sorted(Comparator.comparing(result -> result.attack().id())).toList();
    StringBuilder out = new StringBuilder();
    out.append("# Attack bench report\n\n");
    out.append(
        "Generated by `make attacks` (`aduana attacks run`) against the demo stack. Do not edit by\n");
    out.append(
        "hand: CI regenerates it and fails when it differs. Cases are in [`cases/`](cases/).\n\n");
    out.append(summary(sorted, true)).append('\n');
    out.append(summary(sorted, false)).append("\n\n");
    out.append("| Category | Minimum | Cases | Deterministic stopped | Heuristic stopped |\n");
    out.append("|---|---|---|---|---|\n");
    for (Map.Entry<String, Long> category :
        AttackCase.MINIMUMS.entrySet().stream().sorted(Map.Entry.comparingByKey()).toList()) {
      List<CaseResult> in =
          sorted.stream().filter(r -> r.attack().category().equals(category.getKey())).toList();
      out.append("| ")
          .append(category.getKey())
          .append(" | ")
          .append(category.getValue())
          .append(" | ")
          .append(in.size())
          .append(" | ")
          .append(ratio(in, true))
          .append(" | ")
          .append(ratio(in, false))
          .append(" |\n");
    }
    out.append("\n## Cases\n\n");
    out.append("| Case | Category | Attack | Defence kind | Result | Stopped by |\n");
    out.append("|---|---|---|---|---|---|\n");
    for (CaseResult result : sorted) {
      AttackCase attack = result.attack();
      out.append("| ")
          .append(attack.id())
          .append(" | ")
          .append(attack.category())
          .append(" | ")
          .append(cell(attack.title()))
          .append(" | ")
          .append(attack.deterministic() ? "deterministic" : "heuristic")
          .append(" | ")
          .append(result.stopped() ? "stopped" : "**NOT STOPPED**")
          .append(" | ")
          .append(
              result.stopped()
                  ? cell(attack.defence()) + " (" + cell(String.join("; ", result.observed())) + ")"
                  : "observed: " + cell(String.join("; ", result.observed())))
          .append(" |\n");
    }
    List<CaseResult> escaped = sorted.stream().filter(r -> !r.stopped()).toList();
    out.append("\n## Not stopped\n\n");
    if (escaped.isEmpty()) {
      out.append("None.\n");
    } else {
      for (CaseResult result : escaped) {
        out.append("- ")
            .append(result.attack().id())
            .append(" (")
            .append(result.attack().deterministic() ? "deterministic" : "heuristic")
            .append("): ")
            .append(result.attack().title())
            .append(". Defence: ")
            .append(result.attack().defence())
            .append('\n');
      }
    }
    return out.toString();
  }

  /**
   * Lists the deterministic cases that were not stopped: each one fails the run.
   *
   * @param results the results
   * @return their ids
   * @author Ignacio Rodríguez Caro <rnachoccontact@gmail.com>
   */
  public static List<String> failures(List<CaseResult> results) {
    return results.stream()
        .filter(r -> r.attack().deterministic() && !r.stopped())
        .map(r -> r.attack().id())
        .sorted()
        .toList();
  }

  /**
   * One summary line for deterministic or heuristic defences.
   *
   * @param results the results
   * @param deterministic which kind
   * @return the line
   * @author Ignacio Rodríguez Caro <rnachoccontact@gmail.com>
   */
  private static String summary(List<CaseResult> results, boolean deterministic) {
    List<CaseResult> kind =
        results.stream().filter(r -> r.attack().deterministic() == deterministic).toList();
    long stopped = kind.stream().filter(CaseResult::stopped).count();
    return (deterministic ? "Deterministic" : "Heuristic")
        + " defences: "
        + stopped
        + " of "
        + kind.size()
        + " cases stopped.";
  }

  /**
   * Formats `stopped/total` for one kind in a category.
   *
   * @param results the category's results
   * @param deterministic which kind
   * @return the ratio, or a dash when there are none
   * @author Ignacio Rodríguez Caro <rnachoccontact@gmail.com>
   */
  private static String ratio(List<CaseResult> results, boolean deterministic) {
    List<CaseResult> kind =
        results.stream().filter(r -> r.attack().deterministic() == deterministic).toList();
    return kind.isEmpty()
        ? "-"
        : kind.stream().filter(CaseResult::stopped).count() + "/" + kind.size();
  }

  /**
   * Escapes a table cell.
   *
   * @param text the text
   * @return the text without pipes or line breaks
   * @author Ignacio Rodríguez Caro <rnachoccontact@gmail.com>
   */
  private static String cell(String text) {
    return text.replace("|", "\\|").replace("\n", " ");
  }
}
